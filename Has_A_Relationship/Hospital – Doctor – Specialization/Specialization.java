// a) Create class Specialization having variables (int sid, String field) 

class Specialization{
    
    private int sid;
    private String field;


    public void setSid(int sid){
        this.sid = sid;
    }
    public int getSid(){
        return sid;
    }

    

    public void setField(String Field){
        this.field = Field;
    }
    public String getField(){
        return field;
    }
}